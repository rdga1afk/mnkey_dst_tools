#!/usr/bin/env python3
"""#201 R2: write a .cpp that embeds every shaders/spirv/*.spv (assembler .incbin, no text arrays) and registers the table with the HAL at start-up.
usage: embed_spirv.py <spirv dir> <out.cpp>"""
import sys
from pathlib import Path
src, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2])
files = sorted(src.glob("*.spv"))
L = ['// generated by scripts/embed_spirv.py — do not edit', '#include <monkey_dust/render/gpu_spirv_embed.h>', '#include <cstddef>', '']
for i, f in enumerate(files):
    L.append(f'__asm__(".section .rodata\\n.balign 16\\n.global md_spv_{i}\\nmd_spv_{i}:\\n.incbin \\"{f}\\"\\n.global md_spv_{i}_end\\nmd_spv_{i}_end:\\n.previous\\n");')
    L.append(f'extern "C" const unsigned char md_spv_{i}[]; extern "C" const unsigned char md_spv_{i}_end[];')
L += ['', 'static const md::EmbeddedSpirv kTable[] = {']
for i, f in enumerate(files):
    L.append(f'    {{ "shaders/spirv/{f.name}", md_spv_{i}, (size_t)(md_spv_{i}_end - md_spv_{i}) }},')
L += ['};', 'namespace { struct Registrar { Registrar() { md::RegisterEmbeddedSpirv(kTable, sizeof kTable / sizeof kTable[0]); } } s_registrar; }', '']
new = "\n".join(L)
if not out.exists() or out.read_text() != new:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(new)
print(f"embed_spirv: {len(files)} shaders")
