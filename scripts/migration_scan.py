#!/usr/bin/env python3
"""migration_scan: pre-publication scan of the files that move to tools (MIGRATION_PLAN §1, §5.3, §5.7).
Prints counts per pattern and file:line only (never the matching text). usage: scripts/migration_scan.py [--address-map] [path ...]  (default: game engine tools shaders CMakeLists.txt cmake)
Patterns: (A) Ghidra decompiler identifiers (FUN_/DAT_/LAB_/param_N/local_/uVar...), (B) exe/DLL addresses 14xxxxxxx / 18xxxxxxx / 0x14.. (C) decompiler casts CONCATn/SUBn/undefinedN."""
import os, re, sys, collections
pats = {
 'A_ghidra_id': re.compile(r'\b(FUN_[0-9a-fA-F]{6,}|DAT_[0-9a-fA-F]{6,}|LAB_[0-9a-fA-F]{6,}|PTR_[0-9A-Za-z_]{6,}|param_[0-9]+|in_[A-Z]{2,4}|[ulpc]?[uU]?Var[0-9]+|local_[0-9a-f]{2,})\b'),
 'B_exe_addr': re.compile(r'(?<![\w.])(0x)?1[48][0-9a-fA-F]{7}(?![\w.])(?<!\d{9}f)'),
 'C_decomp_cast': re.compile(r'\b(CONCAT[0-9]{2}|SUB[0-9]{2}|ZEXT[0-9]+|SEXT[0-9]+|undefined[0-9]?|\(code \*\))'),
}
amap = '--address-map' in sys.argv
roots = [a for a in sys.argv[1:] if a != '--address-map'] or ['game','engine','tools','shaders','CMakeLists.txt','cmake']
ext = ('.cpp','.h','.hpp','.c','.cc','.cxx','.inl','.glsl','.frag','.vert','.comp','.lua','.cmake','.txt','.py','.sh','.md','.json')
skip = ('third_party','build','.git','/data/')
tot = collections.Counter(); files = collections.defaultdict(list)
def walk(r):
    if os.path.isfile(r): yield r; return
    for d,ds,fs in os.walk(r):
        if any(s in d+'/' for s in skip): continue
        for f in fs:
            if f.endswith(ext): yield os.path.join(d,f)
for r in roots:
    for p in walk(r):
        try: lines=open(p,errors='replace').read().split('\n')
        except: continue
        for i,l in enumerate(lines,1):
            for k,rx in pats.items():
                if rx.search(l): tot[k]+=1; files[k].append(f'{p}:{i}')
for k in pats: print(k, tot[k], 'lines in', len({x.rsplit(':',1)[0] for x in files[k]}), 'files')
for k in pats:
    c=collections.Counter(x.rsplit(':',1)[0] for x in files[k])
    for f,n in c.most_common(25): print(f'  {k} {n:4d} {f}')

if amap:
    # dry run of MIGRATION_PLAN 5.7: PRIVATE draft (docs/spec/ADDRESS_MAP.md); applies nothing. Our own comments only.
    tok = re.compile(r"(?<![\w.])(?:0x)?1[48][0-9a-fA-F]{7}(?![\w.])|\b(?:FUN|DAT|LAB)_[0-9a-fA-F]{6,}\b")
    rows = []
    for k in ('A_ghidra_id', 'B_exe_addr'):
        for fl in files[k]:
            p, n = fl.rsplit(':', 1); n = int(n)
            if p.endswith(('miniaudio.h', 'stb_image.h')) or 'third_party' in p: continue
            rows.append((p, n))
    seen = sorted(set(rows)); out = ['# ADDRESS_MAP (private draft, generated by scripts/migration_scan.py --address-map)', '',
      'MIGRATION_PLAN 5.7: public code keeps behaviour text, addresses live here. Nothing applied yet. Level column to fill from the reading log.', '',
      '| file:line | addresses | proposed comment (addresses removed) |', '|---|---|---|']
    for p, n in seen:
        l = open(p, errors='replace').read().split('\n')[n - 1]
        adr = sorted(set(m.group(0) for m in tok.finditer(l)))
        if not adr: continue
        pro = re.sub(r"\s*\([^()]*(?:%s)[^()]*\)" % tok.pattern, '', l)
        pro = tok.sub('', pro); pro = re.sub(r"\s{2,}", ' ', pro).rstrip(' ,;:')
        out.append(f"| {p}:{n} | {', '.join(adr)} | `{pro.strip()[:200].replace('|', '/')}` |")
    os.makedirs('docs/spec', exist_ok=True)
    open('docs/spec/ADDRESS_MAP.md', 'w').write('\n'.join(out) + '\n')
    print('address map rows:', len(out) - 7, '-> docs/spec/ADDRESS_MAP.md')
