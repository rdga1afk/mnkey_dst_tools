#!/usr/bin/env python3
"""#201 R5: write a .cpp that embeds the given data files (assembler .incbin) and registers them with md::RegisterEmbeddedFiles at start-up.
usage: embed_data.py <out.cpp> <key=file>...   (key = the repo-relative path the code asks DataPath for, e.g. game/data/terrain_config.txt; file = where it is on disk)"""
import sys
from pathlib import Path
out = Path(sys.argv[1]); root = Path(__file__).resolve().parent.parent
files = [a.split('=', 1) for a in sys.argv[2:]]   # [key, file]
L = ['// generated by scripts/embed_data.py — do not edit', '#include <monkey_dust/io/data_files.h>', '#include <cstddef>', '']
for i, f in enumerate(files):
    f, p = f[0], Path(f[1]).resolve()
    L.append(f'__asm__(".section .rodata\\n.balign 16\\n.global md_data_{i}\\nmd_data_{i}:\\n.incbin \\"{p}\\"\\n.global md_data_{i}_end\\nmd_data_{i}_end:\\n.previous\\n");')
    L.append(f'extern "C" const unsigned char md_data_{i}[]; extern "C" const unsigned char md_data_{i}_end[];')
L += ['', 'static const md::EmbeddedFile kTable[] = {']
for i, (f, _p) in enumerate(files):
    L.append(f'    {{ "{f}", md_data_{i}, (size_t)(md_data_{i}_end - md_data_{i}) }},')
L += ['};', 'namespace { struct Registrar { Registrar() { md::RegisterEmbeddedFiles(kTable, sizeof kTable / sizeof kTable[0]); } } s_registrar; }', '']
new = "\n".join(L)
if not out.exists() or out.read_text() != new:
    out.parent.mkdir(parents=True, exist_ok=True); out.write_text(new)
print(f"embed_data: {len(files)} files")
